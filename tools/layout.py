#!/usr/bin/env python3
"""Where things live: the repo root, working copies, tool output (A51-1).

    python tools/layout.py where              the real root, staging home, out folder
    python tools/layout.py build              rewrite docs/LAYOUT.md from config/layout.json
    python tools/layout.py check              root entries that are not in the map

One source for paths that fifteen tools each worked out for themselves
("parent if my name starts with .staging"). That rule broke the day working
copies moved into .staging/<name> (user 2026-10-27: twenty .staging-* folders
at the root): a copy's parent is now .staging, not the root. The real root is
the parent of the OUTERMOST folder whose name has the staging prefix, which
covers .staging, .staging-xxx (old) and .staging/xxx (new) alike.

The data is config/layout.json; this file only reads it.
"""
import json
import re
import subprocess
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent.parent
MARK = "<!-- generated by tools/layout.py below this line - edit config/layout.json -->"


def _load_json(path):
    # config/*.json may carry // comments (the hub's loader strips them)
    text = Path(path).read_text(encoding="utf-8")
    return json.loads(re.sub(r"(?m)^\s*//.*$", "", text))


class RepoLayout:
    """The repo seen from any file inside it, main tree or a working copy."""

    def __init__(self, start=HERE):
        self.data = _load_json(self._find_config(Path(start).resolve()))
        st = self.data["staging"]
        self.prefix = st["prefix"]
        self.work = self.tree_of(Path(start).resolve())
        self.real = self.real_root(self.work, self.prefix)
        self.staging_home = self.real / st["home"]
        self.out_home = self.real / self.data["out"]["home"]

    @staticmethod
    def _find_config(start):
        for p in (start, *start.parents):
            f = p / "config" / "layout.json"
            if f.is_file():
                return f
        return HERE / "config" / "layout.json"

    @staticmethod
    def tree_of(start):
        """The tree (main or a copy) this path is in: nearest folder with tools/."""
        for p in (start, *start.parents):
            if (p / "tools" / "layout.py").is_file():
                return p
        return start

    @staticmethod
    def real_root(path, prefix=".staging"):
        """Parent of the outermost folder named with the prefix, else path."""
        path = Path(path).resolve()
        top = None
        for p in (path, *path.parents):
            if p.name.startswith(prefix):
                top = p
        return top.parent if top is not None else path

    def is_copy_part(self, name):
        """True for a working-copy folder or a staging bookkeeping file."""
        return str(name).startswith(self.prefix)

    @property
    def in_copy(self):
        return self.work != self.real

    def tree(self, name=None):
        """Where the working copy called name is. A path with a separator is
        taken as given (relative to the root); a bare name goes in the home.
        An old flat .staging (a tree, not a home) is still found."""
        name = name or self.data["staging"]["default"]
        p = Path(name)
        if p.is_absolute():
            return p
        if len(p.parts) > 1 or p.name.startswith(self.prefix):
            legacy = self.real / p
            if p.name == self.data["staging"]["home"] and (legacy / "promote.py").is_file():
                return legacy                       # old flat .staging tree
            if p.name == self.data["staging"]["home"]:
                return self.staging_home / self.data["staging"]["default"]
            return legacy
        return self.staging_home / name

    def book(self, key):
        """A staging bookkeeping file (landed log, tree list, locks)."""
        self.staging_home.mkdir(parents=True, exist_ok=True)
        return self.staging_home / self.data["staging"]["books"][key]

    def out(self, kind):
        if kind not in self.data["out"]["kinds"]:
            raise KeyError("unknown output kind %r: add it to config/layout.json" % kind)
        return self.out_home / kind

    # ---- the root map ------------------------------------------------------
    def allowed(self):
        r = self.data["root"]
        return set(r["files"]) | set(r["dirs"])

    def tolerated(self):
        return set(self.data["root"]["tolerated"]["names"])

    def root_report(self, root=None):
        """(unexpected, tolerated) names at the root of a tree."""
        root = Path(root or self.work)
        allowed, soft = self.allowed(), self.tolerated()
        bad, meh = [], []
        for p in sorted(root.iterdir()):
            n = p.name
            if n in allowed:
                continue
            if n in soft or self.is_copy_part(n) or self._ignored(n):
                meh.append(n)
            else:
                bad.append(n)
        return bad, meh

    def _ignored(self, name):
        if not (self.real / ".git").exists():
            return False
        try:
            r = subprocess.run(["git", "-C", str(self.real), "check-ignore", "-q", name],
                               capture_output=True, timeout=20)
            return r.returncode == 0
        except (OSError, subprocess.SubprocessError):
            return False

    def render_map(self):
        r, st, out = self.data["root"], self.data["staging"], self.data["out"]
        lines = ["", "## Root folders", "", "| Folder | What lives there |", "| --- | --- |"]
        lines += ["| `%s/` | %s |" % (k, v) for k, v in sorted(r["dirs"].items())]
        lines += ["", "## Root files", "", "| File | What it is |", "| --- | --- |"]
        lines += ["| `%s` | %s |" % (k, v) for k, v in sorted(r["files"].items())]
        lines += ["", "## Working copies", "",
                  "`%s/<task>` (default `%s/%s`): `python promote.py --staging <task>`."
                  % (st["home"], st["home"], st["default"]),
                  "", "## Tool output (git-ignored)", ""]
        lines += ["- `%s/%s/`: %s" % (out["home"], k, v) for k, v in sorted(out["kinds"].items())]
        lines += ["", "Inside a folder, `python tools/systems.py which <file>` names the",
                  "system and its header in `docs/systems/`.", ""]
        return "\n".join(lines)

    def map_path(self):
        return self.work / "docs" / "LAYOUT.md"

    def map_is_current(self):
        p = self.map_path()
        if not p.is_file():
            return False
        text = p.read_text(encoding="utf-8")
        return MARK in text and text.split(MARK, 1)[1] == self.render_map()

    def build_map(self):
        p = self.map_path()
        head = p.read_text(encoding="utf-8").split(MARK, 1)[0] if p.is_file() else \
            "# Repo layout\n\nWhere things live. Edit `config/layout.json`, then " \
            "`python tools/layout.py build`.\n\n"
        with open(p, "w", encoding="utf-8", newline="\n") as f:
            f.write(head + MARK + self.render_map())
        return p


def main(argv):
    L = RepoLayout()
    cmd = argv[0] if argv else "where"
    if cmd == "where":
        print("tree     %s\nreal     %s\nstaging  %s\nout      %s"
              % (L.work, L.real, L.staging_home, L.out_home))
        return 0
    if cmd == "build":
        print("wrote %s" % L.build_map())
        return 0
    if cmd == "check":
        bad, meh = L.root_report()
        for n in bad:
            print("NOT IN MAP  %s  (move it, or add it to config/layout.json)" % n)
        for n in meh:
            print("local only  %s" % n)
        return 1 if bad else 0
    print(__doc__)
    return 2


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
