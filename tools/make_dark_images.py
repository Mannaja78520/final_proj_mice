"""Dark-theme versions of the drawn pictures (user 2026-11-23: dark theme = dark picture).

    python tools/make_dark_images.py

For every shared/web/img/apps/<n>.webp and img/help/<n>.webp it writes <n>-dark.webp:
  * app icons: the flat plate behind the character is darkened (same hue, less bright),
    the character and its outline are untouched;
  * help pictures: the cream background becomes transparent, so the page's own card
    colour shows through whichever dark theme is on.
The CSS that swaps them is generated into shared/web/img-dark.css (one rule per picture,
dark themes listed in DARK_THEMES). Re-run after redrawing a picture.
"""
import colorsys
import json
from collections import deque
from pathlib import Path

from PIL import Image

ROOT = Path(__file__).resolve().parent.parent / "shared" / "web"
DARK_THEMES = ["midnight", "carnival"]       # themes.css themes with color-scheme: dark


def flood(img, seed, tol):
    """Pixels connected to seed whose colour is within tol (sum of channel gaps) of it."""
    w, h = img.size
    px = img.load()
    base = px[seed]
    seen = bytearray(w * h)
    out = []
    q = deque([seed])
    seen[seed[1] * w + seed[0]] = 1
    while q:
        x, y = q.popleft()
        out.append((x, y))
        for nx, ny in ((x + 1, y), (x - 1, y), (x, y + 1), (x, y - 1)):
            if 0 <= nx < w and 0 <= ny < h and not seen[ny * w + nx]:
                seen[ny * w + nx] = 1
                p = px[nx, ny]
                if p[3] > 200 and sum(abs(p[i] - base[i]) for i in range(3)) <= tol:
                    q.append((nx, ny))
    return out


def dark_icon(src):
    im = Image.open(src).convert("RGBA")
    px = im.load()
    for seed in ((8, 8), (im.width - 9, 8), (8, im.height - 9), (im.width - 9, im.height - 9)):
        if px[seed][3] < 200:
            continue
        for x, y in flood(im, seed, 60):
            r, g, b, a = px[x, y]
            hh, s, v = colorsys.rgb_to_hsv(r / 255, g / 255, b / 255)
            r2, g2, b2 = colorsys.hsv_to_rgb(hh, min(1, s * 0.8), 0.30 + 0.22 * v)
            px[x, y] = (int(r2 * 255), int(g2 * 255), int(b2 * 255), a)
    return im


def dark_help(src):
    im = Image.open(src).convert("RGBA")
    px = im.load()
    bg = set()
    for seed in ((2, 2), (im.width - 3, 2), (2, im.height - 3), (im.width - 3, im.height - 3)):
        bg.update(flood(im, seed, 36))
    mask = Image.new("L", im.size, 0)
    mp = mask.load()
    for x, y in bg:
        mp[x, y] = 255
    # one pixel wider than the flood, so no cream rim is left round the outlines
    from PIL import ImageFilter
    mask = mask.filter(ImageFilter.MaxFilter(3)).filter(ImageFilter.GaussianBlur(0.6))
    for y in range(im.height):
        for x in range(im.width):
            r, g, b, a = px[x, y]
            m = mp[x, y]
            if m:
                px[x, y] = (r, g, b, int(a * (255 - m) / 255))
    return im


def main():
    rules = []
    for sub, fn in (("apps", dark_icon), ("help", dark_help)):
        for f in sorted((ROOT / "img" / sub).glob("*.webp")):
            if f.name.endswith("-dark.webp") or (sub == "apps" and f.stem == "help"):
                continue
            out = f.with_name(f.stem + "-dark.webp")
            fn(f).save(out, "WEBP", quality=90, method=6)
            rules.append("/img/%s/%s" % (sub, f.stem))
    sel = lambda t, r: 'html[data-theme="%s"] img[src="%s.webp"]{content:url(%s-dark.webp)}' % (t, r, r)
    css = ["/* GENERATED by tools/make_dark_images.py - dark themes show the dark picture. */"]
    for r in rules:
        css += [sel(t, r) for t in DARK_THEMES]
    (ROOT / "img-dark.css").write_text("\n".join(css) + "\n", encoding="utf-8")
    print(json.dumps(rules))


if __name__ == "__main__":
    main()
