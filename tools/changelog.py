"""Change log for every change: one small file per change, one generated page.

    python tools/changelog.py new <slug> "<plain one-line title>" --kind new|improved|fixed --area <area> [--pr N] (today's date)
    python tools/changelog.py build                                        write docs/CHANGELOG.md
    python tools/changelog.py check                                        validate (QC runs this)

WHY (user 2026-11-25): the project report needs "which version changed which
part, how it works, what the problem was, which method fixed it". A single
shared CHANGELOG.md would clash when agents work in parallel (same reason as
handoff/tasks/), so each change is its own file in docs/changelog/entries/ and
docs/CHANGELOG.md is generated from them (newest first, one heading per day =
the "version"; the PR number is the version tag inside it).
Style = game patch notes (user 2026-11-25): short, plain, non-engineer wording; notable items
keep a one-line Problem/Method/Numbers so the report book can still trace the method.
Group trivial fixes (typo, spacing) into one entry.
Public repo: no keys, no friend code, no private data.
"""
import datetime
import pathlib
import re
import sys

ROOT = pathlib.Path(__file__).resolve().parent.parent
ENTRIES = ROOT / "docs" / "changelog" / "entries"
PAGE = ROOT / "docs" / "CHANGELOG.md"
# Fields every entry carries, in page order. Data, not code: add a name to extend.
KINDS = (("new", "New"), ("improved", "Improved"), ("fixed", "Fixed"))   # page order; data
FIELDS = ("Problem", "Method", "Numbers")          # optional sub-lines, only for notable items
REQUIRED = ()
HEAD = re.compile(r"\A---\ndate: (\d{4}-\d{2}-\d{2})\nkind: (new|improved|fixed)\nprs: ([^\n]*)\narea: ([a-z0-9-]+)\ntitle: ([^\n]+)\n---\n", re.S)
SECRET = re.compile(r"(sk-[A-Za-z0-9]{20,}|AIza[0-9A-Za-z_-]{30,}|ghp_[A-Za-z0-9]{30,}|-----BEGIN [A-Z ]*PRIVATE KEY)")
TEMPLATE = """---
date: {date}
kind: {kind}
prs: {pr}
area: {area}
title: {title}
---
Problem: (optional, notable items only) what was wrong, one line.
Method: (optional) how we solved it, one line.
Numbers: (optional) measured before/after; link docs/experiments/.
"""


def parse(path):
    text = path.read_text(encoding="utf-8").replace("\r\n", "\n")
    m = HEAD.match(text)
    if not m:
        return None
    body = text[m.end():]
    fields = {}
    for name in FIELDS:
        f = re.search(r"^%s:[ \t]*(.*?)(?=^(?:%s):|\Z)" % (name, "|".join(FIELDS)), body, re.S | re.M)
        if f:
            fields[name] = f.group(1).strip()
    prs = [p.strip().lstrip("#") for p in m.group(3).split(",") if p.strip() and p.strip() != "-"]
    return {"date": m.group(1), "prs": prs, "kind": m.group(2), "area": m.group(4), "title": m.group(5).strip(),
            "fields": fields, "file": path.name, "text": text}


def entries():
    return [(p, parse(p)) for p in sorted(ENTRIES.glob("*.md"))]


def problems():
    bad = []
    for p, e in entries():
        if e is None:
            bad.append("%s: header must be ---/date/kind/prs/area/title/---" % p.name)
            continue
        try:
            datetime.date.fromisoformat(e["date"])
        except ValueError:
            bad.append("%s: bad date" % p.name)
        if not p.name.startswith(e["date"]):
            bad.append("%s: file name must start with its date" % p.name)
        for r in REQUIRED:
            if not e["fields"].get(r):
                bad.append("%s: fill in '%s:'" % (p.name, r))
        for name, val in e["fields"].items():
            if val.startswith("(optional"):
                bad.append("%s: delete or fill the '%s:' placeholder" % (p.name, name))
        if SECRET.search(e["text"]):
            bad.append("%s: looks like a secret (public repo)" % p.name)
    if PAGE.exists() and PAGE.read_text(encoding="utf-8").replace("\r\n", "\n") != render():
        bad.append("docs/CHANGELOG.md is stale: run python tools/changelog.py build")
    elif not PAGE.exists():
        bad.append("docs/CHANGELOG.md missing: run python tools/changelog.py build")
    return bad


def render():
    rows = [e for _, e in entries() if e]
    rows.sort(key=lambda e: (e["date"], e["file"]), reverse=True)
    out = ["# Change log", "",
           "Generated by `python tools/changelog.py build` from `docs/changelog/entries/`. Do not edit by hand.",
           "One heading per day (the version), changes grouped New / Improved / Fixed, one plain line each; notable ones carry a short Problem / Method / Numbers sub-line.", ""]
    for day in sorted({e["date"] for e in rows}, reverse=True):
        out += ["## %s" % day, ""]
        for kind, label in KINDS:
            mine = [e for e in rows if e["date"] == day and e["kind"] == kind]
            if not mine:
                continue
            out += ["**%s**" % label, ""]
            for e in mine:
                tag = " (%s)" % ", ".join("#" + p for p in e["prs"]) if e["prs"] else ""
                out.append("- %s%s — `%s`" % (e["title"], tag, e["area"]))
                sub = [" ".join(e["fields"][n].split()) for n in FIELDS if e["fields"].get(n)]
                for n, v in zip([n for n in FIELDS if e["fields"].get(n)], sub):
                    out.append("  - *%s:* %s" % (n, v))
            out.append("")
    return "\n".join(out) + "\n"


def slugify(s):
    return re.sub(r"[^a-z0-9]+", "-", s.lower()).strip("-")[:50] or "change"


def main(argv):
    if not argv or argv[0] not in ("new", "build", "check"):
        print(__doc__)
        return 2
    if argv[0] == "build":
        PAGE.write_bytes(render().encode("utf-8"))
        print("wrote", PAGE.relative_to(ROOT))
        return 0
    if argv[0] == "check":
        bad = problems()
        print("\n".join(bad) or "changelog ok")
        return 1 if bad else 0
    if len(argv) < 3:
        print(__doc__)
        return 2
    area, pr, kind = "misc", "-", "improved"
    rest = argv[3:]
    for i, a in enumerate(rest):
        if a == "--area" and i + 1 < len(rest):
            area = rest[i + 1]
        if a == "--kind" and i + 1 < len(rest):
            kind = rest[i + 1]
        if a == "--pr" and i + 1 < len(rest):
            pr = rest[i + 1]
    date = datetime.date.today().isoformat()
    path = ENTRIES / ("%s-%s.md" % (date, slugify(argv[1])))
    ENTRIES.mkdir(parents=True, exist_ok=True)
    path.write_text(TEMPLATE.format(date=date, kind=kind, pr=pr, area=area, title=argv[2]), encoding="utf-8", newline="\n")
    print("created", path.relative_to(ROOT), "- fill it in, then run: python tools/changelog.py build")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
