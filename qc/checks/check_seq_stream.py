"""The board plays a big show one step at a time, never the whole file at once.

Lab 2026-10-28, nong 67 over WiFi: `MOVE` of a v5 cheer dance (447 poses,
~30 KB) gave no reply for 60 s and the board restarted (`reset=CRASH`, boots
2 -> 4, twice). A 231 B file played in 114 ms. SequencePlayer::startAt parsed
the WHOLE file with deserializeYml into one JsonDocument inside the web
request (SDStore::loadYaml). The PC split the dance into 30-pose files chained
with `next:` to get through the lab.

The fix: firmware/src/core/SeqScan.h scans the lines once (header keys, where
the steps are, how many) and hands over one step's text when it is due; each
step is parsed into one small reused document. SeqScan is plain C++, so this
check COMPILES it with the PC's g++ and runs it on generated shows:

* a 447-pose ~30 KB show: every step comes back, in order, with its comment
  and its second key (`wait:` under the dash), and the header keeps `next:`
  written AFTER the steps;
* reads of 7 bytes (a step split across every refill) give the same steps;
* CRLF line ends, steps at column 0, blank and comment lines between steps;
* `steps: [...]` (flow style) is refused with a reason, not half played;
* the scanner's own memory is fixed (< 1 KB) and no item is bigger than one
  step, whatever the show's length;
* SequencePlayer no longer calls loadYaml / keeps a `steps` JsonArray.

Not tested on the board yet: flashing waits for the next lab day.
"""
from pathlib import Path
import shutil
import subprocess
import tempfile

import qc as F

AREA = "sequences"
TITLE = "a big show plays one step at a time (no whole-file parse on MOVE)"
SLOW = False

PLAYER = F.FIRMWARE / "src" / "core" / "SequencePlayer.cpp"
POSES = 447


def _show(n, crlf=False, col0=False, flow=False):
    """A Studio-shaped show and the items the board must get back."""
    ind = "" if col0 else "  "
    lines = ["# generated by Nong Studio", "name: big", "loop: false"]
    items = []
    if flow:
        lines.append('steps: [{pose: "90 T 500"}]')
    else:
        lines.append("steps:")
        lines.append(ind + "- pace: music 0")
        items.append("- pace: music 0\n")
        for i in range(n):
            pose = '- pose: "%d 120.9 155 25 25 56.5 25 25 90 90 T %d"    # move %d' % (
                i % 180, 300 + i, i)
            lines.append(ind + pose)
            text = pose + "\n"
            if i % 50 == 7:
                lines.append(ind + "  wait: %d" % i)
                text += "  wait: %d\n" % i
            if i % 97 == 3:
                lines.append("")
                lines.append("# a section note at column 0")
            items.append(text)
    lines.append("next: part2.yaml")
    end = "\r\n" if crlf else "\n"
    return end.join(lines) + end, items


def _run_exe(exe, path, chunk):
    out = subprocess.run([str(exe), str(path), str(chunk)], capture_output=True,
                         text=True, timeout=30).stdout
    res = {"items": []}
    for line in out.splitlines():
        key, _, val = line.partition(" ")
        val = val.replace("\\n", "\n").replace("\\\\", "\\")
        if key == "ITEM":
            res["items"].append(val)
        else:
            res[key] = val
    return res


def run(t):
    src = PLAYER.read_text(encoding="utf-8")
    t.ok("loadYaml" not in src, "MOVE no longer parses the whole file (no loadYaml in the player)",
         "SequencePlayer.cpp still calls loadYaml")
    t.ok('["steps"]' not in src, "the player keeps no whole steps array in memory")
    t.ok("scan_.next(" in src, "the player takes the next step from the scanner")

    cxx = shutil.which("g++") or shutil.which("clang++")
    if not t.ok(bool(cxx), "host C++ compiler exists; the stream proof cannot be skipped"):
        return
    with tempfile.TemporaryDirectory(prefix="mice_seq_stream_") as folder:
        folder = Path(folder)
        exe = folder / "seq.exe"
        built = subprocess.run([cxx, "-std=c++17", "-Wall", "-Wextra", "-Werror",
                                "-I", str(F.FIRMWARE / "src"), str(F.QC / "data/seq_stream.cpp"),
                                "-o", str(exe)], capture_output=True, text=True, timeout=90)
        if not t.ok(built.returncode == 0, "SeqScan.h compiles on the PC", built.stderr[-2000:]):
            return
        cases = [("big", _show(POSES), 512), ("tiny reads", _show(POSES), 7),
                 ("crlf", _show(60, crlf=True), 512), ("column 0", _show(60, col0=True), 13)]
        for name, (text, items), chunk in cases:
            path = folder / (name.replace(" ", "_") + ".yaml")
            path.write_bytes(text.encode("utf-8"))
            if name == "big":
                t.ok(len(text) > 28000, "the big show is the lab's size (~30 KB)", str(len(text)))
            r = _run_exe(exe, path, chunk)
            if not t.ok("ERR" not in r, "%s: the show is accepted" % name, r.get("ERR", "")):
                continue
            t.ok(r.get("COUNT") == str(len(items)), "%s: every step counted" % name,
                 "%s vs %d" % (r.get("COUNT"), len(items)))
            t.ok(r["items"] == items, "%s: every step comes back whole and in order" % name,
                 next(("step %d: %r vs %r" % (i, a, b) for i, (a, b) in
                       enumerate(zip(r["items"], items)) if a != b), "count %d" % len(r["items"])))
            t.ok("next: part2.yaml" in r.get("HEADER", "") and "steps" not in r.get("HEADER", ""),
                 "%s: header keeps next: after the steps, not the steps" % name, r.get("HEADER", ""))
            t.ok(r.get("FAILED") == "0" and r.get("REWIND") == "1" and r.get("FIRST") == items[0],
                 "%s: a loop starts again at the first step" % name, str(r.get("FIRST")))
            if name == "big":
                t.ok(int(r.get("SIZEOF", "99999")) < 1024, "the scanner's memory is fixed (< 1 KB)",
                     r.get("SIZEOF"))
                t.ok(int(r.get("BIGGEST", "99999")) < 200, "no step needs more than one step's text",
                     r.get("BIGGEST"))
        flow = folder / "flow.yaml"
        flow.write_bytes(_show(0, flow=True)[0].encode("utf-8"))
        r = _run_exe(exe, flow, 512)
        t.ok("one - item per line" in r.get("ERR", ""), "flow-style steps are refused with a reason",
             str(r))
